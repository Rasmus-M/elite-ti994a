# Converts the MSX title music (elite.skool, $7A1C-$8204) to src/title-music.a99 for the SN76489.
# Run from the repo root: python tools/convert-title-music.py
import re

SKOOL = '../elite-msx-skoolkit/src/elite.skool'
OUT = 'src/title-music.a99'

mem = {}
labels = {}
pending_label = None
for line in open(SKOOL):
    m = re.match(r'^@label=(\w+)', line)
    if m:
        pending_label = m.group(1)
        continue
    m = re.match(r'^[ bc*]\$([0-9A-F]{4}) (DEF[BW]) ([^;]*)', line)
    if not m:
        if re.match(r'^[ bc*]\$', line):
            pending_label = None
        continue
    a = int(m.group(1), 16)
    if pending_label:
        labels[a] = pending_label
        pending_label = None
    if not 0x7A1C <= a < 0x8205:
        continue
    for v in m.group(3).split(','):
        v = int(v.strip().lstrip('$'), 16)
        if m.group(2) == 'DEFB':
            mem[a] = v
            a += 1
        else:
            mem[a], mem[a + 1] = v & 255, v >> 8
            a += 2

def word(a):
    return mem[a] | mem[a + 1] << 8

SILENT = 0x90
LOOP = 0x91
MAX_PERIOD = 1023  # the SN76489's tone period is 10 bits
periods = [word(0x7A1C + 2 * i) for i in range(73)]

header = 0x7AE4
channels = mem[header]
chans = []
for c in range(channels):
    lst = word(header + 1 + 3 * c)
    vol = mem[header + 3 + 3 * c]
    pats = []
    a = lst
    while word(a):
        pats.append(word(a))
        a += 2
    chans.append((lst, vol, pats))

def pattern_label(a):
    if a == 0x8202:
        return 'title_music_rest'
    return labels[a]

def list_label(c):
    return ['title_music_patterns', 'title_music_channel_2', 'title_music_channel_3'][c]

# Notes too low for the SN76489 go up an octave (12 notes = 24 bytes of the period table)
transposed = 0
pattern_bytes = {}
for c, (lst, vol, pats) in enumerate(chans):
    for p in pats:
        out = []
        a = p
        while mem[a] != LOOP:
            note, dur = mem[a], mem[a + 1]
            if note < SILENT:
                while periods[note // 2] > MAX_PERIOD:
                    note += 24
                    transposed += 1
            if p in pattern_bytes and pattern_bytes[p][len(out) // 2 * 2:len(out) // 2 * 2 + 2] not in ([], [note, dur]):
                raise SystemExit('pattern %04X is shared by channels with different transposition' % p)
            out += [note, dur]
            a += 2
        pattern_bytes[p] = out + [LOOP]

def sn(p):
    # SN76489 tone command bytes without the channel bits: the low 4 bits, then the high 6 bits
    return (p & 15) << 8 | p >> 4

L = []
L.append('* Title music, converted from the MSX version (#R$7A1C-#R$8204) for the SN76489')
L.append('*')
L.append('* Generated by tools/convert-title-music.py - don\'t edit by hand.')
L.append('* The tone periods are the MSX ones (the PSG and the SN76489 give the same')
L.append('* frequency for the same period), converted to the SN76489\'s command bytes.')
L.append('* The SN76489 can\'t play periods above 1023, so %d bass notes on channel 3 are' % transposed)
L.append('* an octave higher than on the MSX.')
L.append('')
L.append('*' * 80)
L.append('* Note tone periods')
L.append('*')
L.append('* For each of 72 notes (#R$7A1C), lowest first, the high byte is the low 4')
L.append('* bits of the tone period (for the first command byte) and the low byte the')
L.append('* high 6 bits (the second byte). Indexed by the note byte (note * 2).')
L.append('* Notes at or above >90 are silent.')
L.append('       even')
L.append('note_tone_periods:')
for i in range(0, 72, 8):
    L.append('       data ' + ','.join('>%04x' % sn(min(p, MAX_PERIOD)) for p in periods[i:i + 8]))
L.append('')
L.append('*' * 80)
L.append('* Title music')
L.append('*')
L.append('* The tune header (#R$7AE4): the number of channels, then for each channel')
L.append('* the address of its pattern list and its attenuation (15 - the MSX volume).')
L.append('title_music:')
L.append('       data %d' % channels)
for c, (lst, vol, pats) in enumerate(chans):
    L.append('       data %s,%d%s; channel %d' % (list_label(c), 15 - vol, ' ' * (30 - len(list_label(c))), c + 1))
L.append('')
L.append('*' * 80)
L.append('* Title music: pattern lists')
L.append('*')
L.append('* One list per channel (#R$7AEE): the patterns to play in turn, ending with 0.')
for c, (lst, vol, pats) in enumerate(chans):
    L.append(list_label(c) + ':')
    for p in pats:
        L.append('       data ' + pattern_label(p))
    L.append('       data 0')
L.append('')
L.append('*' * 80)
L.append('* Title music: note data')
L.append('*')
L.append('* (note, duration) byte pairs (#R$7B18), each pattern ending with >91. A')
L.append('* duration with bit 7 set has a silent last tick.')
done = set()
for c, (lst, vol, pats) in enumerate(chans):
    for p in pats:
        if p in done:
            continue
        done.add(p)
        L.append(pattern_label(p) + ':')
        b = pattern_bytes[p]
        for i in range(0, len(b), 8):
            L.append('       byte ' + ','.join('>%02x' % v for v in b[i:i + 8]))
L.append('')
L.append('title_music_end:')
L.append('       equ  $')
open(OUT, 'w', newline='\r\n').write('\n'.join(L) + '\n')
print('transposed', transposed, 'bytes', sum(len(v) for v in pattern_bytes.values()))
