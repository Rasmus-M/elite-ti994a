def half(rows):
    cols = [c for r in rows for c, ch in enumerate(r) if ch == '#']
    x = min(cols) if cols else 8
    assert not cols or max(cols) - x < 16, 'a half is wider than 16 pixels'
    x = min(x, 16)
    out = []
    for part in (0, 8):                 # a sprite pattern is its left 8 columns, then its right 8
        for r in rows:
            v = 0
            for b in range(8):
                if r[x + part + b:x + part + b + 1] == '#':
                    v |= 0x80 >> b
            out.append(v)
    return x, out

def rle(data):
    out = []
    i = 0
    while i < len(data):
        j = i
        while j < len(data) and data[j] == data[i] and j - i < 255:
            j += 1
        out += [j - i, data[i]]
        i = j
    return out

lines = []
grids = []
for label, addr, text, art in DESIGNS:
    rows = [r for r in art.strip().split('\n')]
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), label
    grids.append(rows)
    x1, p1 = half(rows[:16])
    x2, p2 = half(rows[16:])
    stream = rle(p1 + p2) + [0]
    lines.append((label + ':').ljust(59) + '; >' + addr)
    lines.append(('       byte >%02X,>%02X' % (x1, x2)).ljust(69) + '; ' + text + ': the two sprites\' columns')
    for k in range(0, len(stream), 8):
        lines.append('       byte ' + ','.join('>%02X' % v for v in stream[k:k + 8]))
print('\n'.join(lines))

