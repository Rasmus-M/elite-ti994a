"""Generate the small ships' sprite patterns (src/ship-sprites.a99).

In flight a ship that is small on screen is shown as a sprite rather than drawn
in full (ship_sprite in src/main-code.a99): not its own shape, which can't be
told at that size, but a pentagon - a wedge with a pointed nose - that tumbles,
so that it is seen as a wireframe ship and not as a star. There are FRAMES
frames of it in each of the sizes in SIZES (the pixels across, for a ship of
radius 2, 3, and 4 or 5), in the middle of a 16 x 16 sprite pattern. (The space
station at radius 4 or 5 is drawn in full.)

usage: python tools/ship-sprites.py [preview.png]
(writes src/ship-sprites.a99 and src/ship-sprite-table.a99)
"""
import sys, math

EOL = chr(13) + chr(10)

SIZES = [5, 7, 9]
FRAMES = 8
# The pentagon, nose up (x, y)
SHAPE = [(0.0, 1.15), (0.95, 0.1), (0.6, -1.0), (-0.6, -1.0), (-0.95, 0.1)]
# It turns about an axis that points LEAN degrees away from the viewer, and its
# plane is TILT degrees from being square on that axis: so it is seen from
# LEAN - TILT to LEAN + TILT degrees off face on as it turns, never edge on
LEAN = 30.0
TILT = 25.0

# The patterns go in two free parts of the sprite pattern table (see CLAUDE.md)
AREAS = [(60, 13), (208, 12)]
COUNT = len(SIZES) * FRAMES
assert COUNT <= sum(n for _, n in AREAS)

def pattern_number(i):
    for first, n in AREAS:
        if i < n:
            return first + 4 * i
        i -= n

def rotate(p, u, deg):
    """Rotate the point p about the unit vector u (Rodrigues)"""
    t = math.radians(deg)
    c, s = math.cos(t), math.sin(t)
    d = sum(a * b for a, b in zip(u, p))
    cr = (u[1] * p[2] - u[2] * p[1], u[2] * p[0] - u[0] * p[2], u[0] * p[1] - u[1] * p[0])
    return tuple(p[i] * c + cr[i] * s + u[i] * d * (1 - c) for i in range(3))

def frame_points(f):
    cx = sum(p[0] for p in SHAPE) / len(SHAPE)
    cy = sum(p[1] for p in SHAPE) / len(SHAPE)
    out = []
    for x, y in SHAPE:
        p = rotate((x - cx, y - cy, 0.0), (1.0, 0.0, 0.0), TILT)
        p = rotate(p, (0.0, 0.0, 1.0), 360.0 * f / FRAMES)
        p = rotate(p, (0.6, 0.8, 0.0), LEAN)
        out.append((p[0], -p[1]))               # y is down on the screen
    return out

ALL = [frame_points(f) for f in range(FRAMES)]
EXTENT = max(max(abs(x), abs(y)) for pts in ALL for x, y in pts)

def render(pts, size):
    k = (size - 1) / 2 / EXTENT
    g = [[0] * 16 for _ in range(16)]
    q = [(int(round(8 + x * k)), int(round(8 + y * k))) for x, y in pts]
    for i in range(len(q)):
        x0, y0 = q[i]; x1, y1 = q[(i + 1) % len(q)]
        steps = max(abs(x1 - x0), abs(y1 - y0), 1)
        for s in range(steps + 1):
            g[int(round(y0 + (y1 - y0) * s / steps))][int(round(x0 + (x1 - x0) * s / steps))] = 1
    return g

grids = []
texts = []
for n, size in enumerate(SIZES):
    for f in range(FRAMES):
        grids.append(render(ALL[f], size))
        texts.append('%d pixels, frame %d' % (size, f))

out = []
out.append('*' * 69)
out.append('*')
out.append("* The small ships' sprite patterns (generated by tools/ship-sprites.py)")
out.append('*')
out.append('* 16x16 sprite patterns (32 bytes: the left 8 columns, then the right 8)')
out.append('* for the ships that are small on screen (ship_sprite in main-code.a99):')
out.append('* %d frames of a tumbling pentagon in each of %d sizes.' % (FRAMES, len(SIZES)))
out.append('* ti_setup_environment uploads the first %d to sprite patterns' % AREAS[0][1])
out.append('* %d on, and the rest to %d on.' % (AREAS[0][0], AREAS[1][0]))
out.append('*')
out.append('ship_sprite_patterns:')
for g, text in zip(grids, texts):
    b = []
    for part in (0, 8):
        for r in range(16):
            b.append(sum((0x80 >> i) for i in range(8) if g[r][part + i]))
    out.append('       byte ' + ','.join('>%02X' % x for x in b[:16]) + ' ; ' + text)
    out.append('       byte ' + ','.join('>%02X' % x for x in b[16:]))
out.append('ship_sprite_patterns_2:')
out.append('       equ  ship_sprite_patterns+%d' % (AREAS[0][1] * 32))
out.append('ship_sprite_patterns_end:')
out.append('       equ  $')
open('src/ship-sprites.a99', 'w', encoding='utf-8', newline='').write(EOL.join(out) + EOL)

out = []
out.append("* The small ships' sprite patterns (ship_sprite): %d frames for each of %d sizes" % (FRAMES, len(SIZES)))
out.append('* (generated by tools/ship-sprites.py)')
out.append('ship_sprite_numbers:')
for n in range(len(SIZES)):
    out.append('       byte ' + ','.join('>%02X' % pattern_number(n * FRAMES + f) for f in range(FRAMES)))
open('src/ship-sprite-table.a99', 'w', encoding='utf-8', newline='').write(EOL.join(out) + EOL)
print('wrote src/ship-sprites.a99 and src/ship-sprite-table.a99: %d patterns' % COUNT)

if len(sys.argv) > 1:
    from PIL import Image
    s = 8
    cols = FRAMES
    rows = (len(grids) + cols - 1) // cols
    im = Image.new('RGB', (cols * 17 * s, rows * 17 * s), (0, 0, 0))
    for n, g in enumerate(grids):
        ox = (n % cols) * 17 * s; oy = (n // cols) * 17 * s
        for y in range(16):
            for x in range(16):
                c = (230, 200, 60) if g[y][x] else (25, 25, 25)
                for dy in range(s - 1):
                    for dx in range(s - 1):
                        im.putpixel((ox + x * s + dx, oy + y * s + dy), c)
    im.save(sys.argv[1])
